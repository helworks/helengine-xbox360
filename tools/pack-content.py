#!/usr/bin/env python3
"""Packs a directory of cooked assets into the archive the guest links in.

The console has no file system, so cooked content travels inside the image.
This writes two files:

  content.bin   the archive itself
  content.S     an assembly stub that places the archive in .rodata and
                exposes hel_content_archive_start and _end

The archive is big-endian, which is the console's own byte order, so the
guest reads its fields directly without swapping. Layout, all offsets
relative to the start of the archive:

  magic   'HELC'
  version u32, currently 1
  count   u32   number of entries
  bytes   u32   total archive size, for a bounds check at load
  entry[count]  path_offset u32, path_length u32, data_offset u32, data_length u32
  paths         each NUL-terminated, so the guest can hand out a C string
  data          each aligned to 16 bytes

An empty archive is valid and is what gets built when no content has been
staged, so the image always links the same way.
"""
import argparse
import os
import struct
import sys

MAGIC = b"HELC"
VERSION = 1
HEADER_BYTES = 16
ENTRY_BYTES = 16
DATA_ALIGNMENT = 16


def collect(root):
    """Returns (relative path with forward slashes, bytes) for every file."""
    entries = []
    if not root or not os.path.isdir(root):
        return entries
    for directory, _, files in os.walk(root):
        for name in sorted(files):
            full = os.path.join(directory, name)
            relative = os.path.relpath(full, root).replace("\\", "/")
            with open(full, "rb") as handle:
                entries.append((relative, handle.read()))
    entries.sort(key=lambda entry: entry[0])
    return entries


def build_archive(entries):
    paths = bytearray()
    path_offsets = []
    for relative, _ in entries:
        path_offsets.append(len(paths))
        paths += relative.encode("utf-8") + b"\0"

    table_bytes = HEADER_BYTES + ENTRY_BYTES * len(entries)
    paths_base = table_bytes
    data_base = paths_base + len(paths)
    data_base = (data_base + DATA_ALIGNMENT - 1) & ~(DATA_ALIGNMENT - 1)

    blobs = bytearray()
    data_offsets = []
    for _, payload in entries:
        padding = (-len(blobs)) % DATA_ALIGNMENT
        blobs += b"\0" * padding
        data_offsets.append(data_base + len(blobs))
        blobs += payload

    total = data_base + len(blobs)
    archive = bytearray()
    archive += MAGIC
    archive += struct.pack(">III", VERSION, len(entries), total)
    for index, (relative, payload) in enumerate(entries):
        archive += struct.pack(
            ">IIII",
            paths_base + path_offsets[index],
            len(relative.encode("utf-8")),
            data_offsets[index],
            len(payload),
        )
    archive += paths
    archive += b"\0" * (data_base - len(archive))
    archive += blobs
    assert len(archive) == total, (len(archive), total)
    return bytes(archive)


def write_stub(path, binary_path):
    """Assembly that links the archive into the image's read-only data."""
    posix = binary_path.replace("\\", "/")
    with open(path, "w", newline="\n") as handle:
        handle.write(
            "/* Generated by tools/pack-content.py. The cooked content archive\n"
            "   travels inside the image because the console has no file\n"
            "   system to read it from. */\n"
            '    .section .rodata.content,"a",@progbits\n'
            "    .balign 16\n"
            "    .globl hel_content_archive_start\n"
            "hel_content_archive_start:\n"
            '    .incbin "' + posix + '"\n'
            "    .globl hel_content_archive_end\n"
            "hel_content_archive_end:\n"
            "    .balign 16\n"
        )


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--content-root", default="",
                        help="directory of staged cooked files; may be absent")
    parser.add_argument("--out-bin", required=True)
    parser.add_argument("--out-stub", required=True)
    parser.add_argument("--incbin-path", default="",
                        help="path the stub uses in .incbin; defaults to --out-bin")
    arguments = parser.parse_args(argv)

    entries = collect(arguments.content_root)
    archive = build_archive(entries)
    os.makedirs(os.path.dirname(arguments.out_bin) or ".", exist_ok=True)
    with open(arguments.out_bin, "wb") as handle:
        handle.write(archive)
    write_stub(arguments.out_stub, arguments.incbin_path or arguments.out_bin)

    print("content entries: %d" % len(entries))
    print("content bytes: %d" % len(archive))
    for relative, payload in entries:
        print("  %s (%d bytes)" % (relative, len(payload)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
